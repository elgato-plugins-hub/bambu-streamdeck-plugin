	window.initI18n = function (infoJson) {
		let lang = "en";
		try {
			const info = typeof infoJson === "string" ? JSON.parse(infoJson) : infoJson;
			lang = String((info && info.application && info.application.language) || "en");
		} catch (e) {}
		const base = lang.split(/[-_]/)[0];
		table = DICT[lang] || DICT[base] || {};
		window.applyI18n();
	};
	window.t = function (key) {
		let s = Object.prototype.hasOwnProperty.call(table, key) ? table[key] : key;
		for (let i = 1; i < arguments.length; i++) s = s.split("{" + (i - 1) + "}").join(String(arguments[i]));
		return s;
	};
